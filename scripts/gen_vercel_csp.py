# -*- coding: utf-8 -*-
"""Generate `vercel.json` — static hosting config for `landing/`, with a real CSP.

## Why this is generated rather than hand-written

The three landing pages carry inline <script> blocks (page-specific bootstrap, 0.1–7.5KB).
A CSP that allows them via `'unsafe-inline'` allows *any* injected script too, which is
most of what a CSP is for. So each block is allowlisted by SHA-256 hash instead.

Hashes are byte-exact. `landing/*.html` is generated by `landing/_gen.py` and committed,
so regenerating a page changes its hash and silently invalidates this file. That is a
stale-artifact bug of exactly the §7.10 shape — except it fails LOUD (the browser blocks
the script and the page visibly breaks) rather than quiet. `--check` makes it fail even
earlier, at CI or pre-deploy, which is where you want it.

    python scripts/gen_vercel_csp.py            # write vercel.json
    python scripts/gen_vercel_csp.py --check    # verify it is current

Exit codes are three-way, per §7.6 — "could not check" must never read as "current":
    0  vercel.json is current
    1  stale: hashes in the file do not match the pages   -> regenerate
    2  could not check (missing pages, unreadable config) -> the harness's problem

## Why `vercel.json` and not `vercel.ts`

`vercel.ts` is Vercel's currently recommended config format and would give this file's job
type-checking. It is deliberately not used: it requires `@vercel/config` from npm, which
means a `package.json` and a Node dependency tree in a repo whose entire dependency list
is four pinned Python packages (§0 — "do not add components"), and it gives Vercel a Node
project to build where today there is nothing to build. The deploy is three static HTML
pages; the config is 30 lines of JSON that this script generates and `--check` verifies.

Revisit if the site ever grows a build step — at that point the Node toolchain is already
paid for and the typing is free.

## What is NOT deployed, and why

Only `landing/` is served. The harness itself is deliberately not hosted: §7.1 gives the
runner exactly one secret (the LLM API key) and forbids a pass-through to real tools, so
putting it behind a public URL would mean a public endpoint that spends a key and runs
agents. `.vercelignore` keeps the Python out of the upload entirely — including
`are/probes/`, which §7.4 keeps referenced by id rather than served as text.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANDING = ROOT / "landing"
OUT = ROOT / "vercel.json"

PAGES = ("index.html", "connect.html", "results.html")

# Inline <script> with no src=. Non-greedy body, DOTALL: the body is hashed verbatim,
# including leading/trailing whitespace, because that is what the browser hashes.
INLINE_SCRIPT = re.compile(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>", re.S)


def script_hashes() -> list[str]:
    """SHA-256 of every inline script body across the pages, as CSP source values."""
    hashes: list[str] = []
    for name in PAGES:
        p = LANDING / name
        if not p.exists():
            raise FileNotFoundError(f"{p} is missing — refusing to emit a CSP that "
                                    f"would silently omit its scripts")
        raw = p.read_bytes()
        # Hash the bytes on disk. Decoding and re-encoding would risk changing them,
        # and .gitattributes pins eol=lf so what is committed is what is served.
        for m in INLINE_SCRIPT.finditer(raw.decode("utf-8")):
            body = m.group(1).encode("utf-8")
            digest = base64.b64encode(hashlib.sha256(body).digest()).decode()
            src = f"'sha256-{digest}'"
            if src not in hashes:
                hashes.append(src)
    if not hashes:
        raise RuntimeError("no inline scripts found — either the pages changed shape or "
                           "the regex is wrong; emitting a CSP now would be guesswork")
    return hashes


def csp(hashes: list[str]) -> str:
    return "; ".join([
        "default-src 'none'",
        # 'self' covers assets/*.js; the hashes cover the per-page bootstrap blocks.
        "script-src 'self' " + " ".join(hashes),
        # 'unsafe-inline' is required by the style="..." attributes in the markup (13 at
        # parse time, plus more built at runtime by the inline scripts). Style attributes
        # cannot be hashed, only nonced or removed, and removing them is a _gen.py
        # refactor. Named here so it reads as a known cost, not an oversight: it permits
        # injected CSS, not injected script.
        "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
        "font-src https://fonts.gstatic.com",
        "img-src 'self' data:",
        # The site never calls the network: data is baked into assets/data.js as
        # window.ARE_DATA. So this is 'none', not 'self'.
        "connect-src 'none'",
        "base-uri 'none'",
        "form-action 'none'",
        "frame-ancestors 'none'",
    ])


def config() -> dict:
    policy = csp(script_hashes())
    security_headers = [
        {"key": "Content-Security-Policy", "value": policy},
        {"key": "X-Content-Type-Options", "value": "nosniff"},
        {"key": "Referrer-Policy", "value": "strict-origin-when-cross-origin"},
        # Vercel terminates TLS and redirects http->https already; HSTS closes the
        # first-request window and is the half Vercel does not do for you.
        {"key": "Strict-Transport-Security",
         "value": "max-age=63072000; includeSubDomains; preload"},
        # frame-ancestors above is the modern control; this is the legacy fallback.
        {"key": "X-Frame-Options", "value": "DENY"},
        {"key": "Permissions-Policy",
         "value": "camera=(), microphone=(), geolocation=(), interest-cohort=()"},
        {"key": "Cross-Origin-Opener-Policy", "value": "same-origin"},
    ]
    return {
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "framework": None,
        "outputDirectory": "landing",
        "headers": [
            {"source": "/(.*)", "headers": security_headers},
            # Content-addressed they are not, so keep HTML revalidating; the assets are
            # small and change with the pages, so a short cache is honest.
            {"source": "/assets/(.*)",
             "headers": [{"key": "Cache-Control",
                          "value": "public, max-age=3600, must-revalidate"}]},
        ],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify vercel.json matches the current pages; do not write")
    args = ap.parse_args()

    try:
        want = config()
    except Exception as exc:                                       # noqa: BLE001
        print(f"COULD NOT BUILD CONFIG ({type(exc).__name__}): {exc}")
        print("Exit 2 = NOT CHECKED. This is not a pass.")
        return 2

    if args.check:
        if not OUT.exists():
            print(f"NOT CHECKED: {OUT.name} does not exist")
            return 2
        try:
            have = json.loads(OUT.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            print(f"NOT CHECKED: {OUT.name} is unreadable ({exc})")
            return 2
        if have == want:
            print(f"{OUT.name} is current ({len(script_hashes())} inline script hash(es)).")
            return 0
        print(f"STALE: {OUT.name} does not match landing/*.html.")
        print("The inline scripts changed, so the committed CSP would block them.")
        print("Fix: python scripts/gen_vercel_csp.py")
        return 1

    OUT.write_text(json.dumps(want, indent=2) + "\n", encoding="utf-8")
    hs = script_hashes()
    print(f"wrote {OUT.name}")
    print(f"  outputDirectory: landing")
    print(f"  inline script hashes: {len(hs)}")
    for h in hs:
        print(f"    {h[:24]}…")
    return 0


if __name__ == "__main__":
    sys.exit(main())
