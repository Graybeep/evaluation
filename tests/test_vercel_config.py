# -*- coding: utf-8 -*-
"""The deploy config is generated from the pages, so it can go stale silently.

`landing/*.html` is generated by `_gen.py` and committed. `vercel.json` allowlists the
pages' inline scripts by SHA-256. Regenerate a page, change a byte, and the committed
hash stops matching — the browser then blocks the script and the deployed site breaks,
while every local check still passes because nothing local reads vercel.json.

That is the §7.10 shape with a deployment on the end of it, so it gets a check rather
than a note in a README.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
VERCEL_JSON = ROOT / "vercel.json"
GEN = ROOT / "scripts" / "gen_vercel_csp.py"


def _policy() -> dict[str, list[str]]:
    cfg = json.loads(VERCEL_JSON.read_text(encoding="utf-8"))
    for rule in cfg["headers"]:
        for h in rule["headers"]:
            if h["key"] == "Content-Security-Policy":
                out = {}
                for part in h["value"].split(";"):
                    bits = part.strip().split()
                    if bits:
                        out[bits[0]] = bits[1:]
                return out
    pytest.fail("no Content-Security-Policy header in vercel.json")


def test_vercel_json_matches_the_committed_pages():
    """The load-bearing one: `--check` exits 0 only when the hashes are current.

    Exit 2 means the generator could not evaluate anything, which is NOT a pass —
    asserting `!= 1` here would sort it into the success bucket, which is the exact
    error this file is named after."""
    r = subprocess.run([sys.executable, str(GEN), "--check"],
                       cwd=str(ROOT), capture_output=True, text=True)
    assert r.returncode == 0, (
        f"vercel.json is stale or uncheckable (exit {r.returncode}).\n"
        f"{r.stdout}{r.stderr}\nFix: python scripts/gen_vercel_csp.py")


def test_the_check_has_teeth():
    """A positive control. Without it, a `--check` that always returned 0 would make
    the test above pass forever — the vacuous-pass shape (§7.10 row 5)."""
    original = VERCEL_JSON.read_text(encoding="utf-8")
    try:
        broken = original.replace("'sha256-", "'sha256-X", 1)
        assert broken != original, "could not mutate a hash — the fixture is wrong"
        VERCEL_JSON.write_text(broken, encoding="utf-8")
        r = subprocess.run([sys.executable, str(GEN), "--check"],
                           cwd=str(ROOT), capture_output=True, text=True)
        assert r.returncode == 1, (
            "a corrupted hash did not report STALE — --check cannot detect drift, "
            "so the test above proves nothing")
    finally:
        VERCEL_JSON.write_text(original, encoding="utf-8")


def test_csp_does_not_fall_back_to_unsafe_inline_for_scripts():
    """The whole point of hashing. 'unsafe-inline' in script-src would allow any
    injected script and make the hashes decorative."""
    p = _policy()
    assert "'unsafe-inline'" not in p.get("script-src", []), (
        "script-src fell back to 'unsafe-inline' — the inline-script hashes are then "
        "cosmetic; either keep the hashes or stop claiming a CSP")
    assert any(s.startswith("'sha256-") for s in p.get("script-src", [])), (
        "no script hashes in script-src")
    assert p.get("default-src") == ["'none'"], "default-src must deny by default"


def test_only_the_landing_directory_is_served():
    """§7.1: the harness holds the API key and has no pass-through. It is not hosted.
    If outputDirectory ever points at the repo root, the Python ships with it."""
    cfg = json.loads(VERCEL_JSON.read_text(encoding="utf-8"))
    assert cfg.get("outputDirectory") == "landing", (
        "outputDirectory must be 'landing' — anything broader publishes the harness")

    ignore = (ROOT / ".vercelignore").read_text(encoding="utf-8")
    lines = [ln.strip() for ln in ignore.splitlines()
             if ln.strip() and not ln.strip().startswith("#")]
    assert "/*" in lines, (
        ".vercelignore must deny by default; an allowlist is what makes a forgotten "
        "new directory fail closed instead of shipping")
    assert "!/landing" in lines, ".vercelignore excludes the one directory being served"
